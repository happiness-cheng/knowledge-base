def _gen_template_notes(start_id, topics, style):
    """生成"定义/特点/场景/风险"模板型笔记。

    ⚠️ 2026-10-10 修正：**每条笔记必须自带特异的 特点/场景/风险**。
    上一版这几段是固定套话（"需要结合具体实现判断，不能一概而论"等），
    导致 35 条生成笔记的正文高度雷同 —— 检索时最邻近的变成了"结构最像"的邻居
    而不是"主题相同"的那条，在 24 条合成 query 上 Hit@1 只有 0.500。
    那不是"检索在真实语料上很差"，而是**我的语料同质**造成的假象。
    现在每条笔记的四个字段都来自该主题的特异内容（见 _TOPICS）。
    """
    out = []
    for k, d in enumerate(topics):
        nid = start_id + k
        title = d['t']
        if style == 'clean':
            body = (f'## {title}\n\n- **定义**\n  {d["gist"]}\n'
                    f'- **特点**\n  {d["feat"]}\n'
                    f'- **场景**\n  {d["scene"]}\n'
                    f'- **风险**\n  {d["risk"]}\n')
        elif style == 'messy':
            # 缩进标题 + 无空行 + 口语尾巴（复刻真实手写笔记的形态），
            # 但内容仍是该主题特异的
            body = (f'  ## {title}\n'
                    f'   - **定义**  {d["gist"]}\n'
                    f'   - **特点**  {d["feat"]}\n'
                    f'   - **风险**  {d["risk"]}\n'
                    f'   记一下：{d["k"]} 这块我踩过坑\n')
        else:  # deep：带 ### 子层，内容同样特异
            # ⚠️ 第二处同质化（2026-10-10 修）：上一版"怎么用"固定写
            # "先小流量验证，观察指标再放量"，3 条 deep 笔记因此共用同一句话，
            # 检索时命中同批邻居。现在改为引用该主题的"场景"字段。
            body = (f'## {title}\n\n### 是什么\n\n{d["gist"]}\n\n### 什么时候用\n\n'
                    f'{d["scene"]}\n\n### 坑在哪\n\n{d["risk"]}\n')
        out.append((nid, title, f'gen_{style}', '2026-09-20', body))
    return out


def _gen_incident_logs(start_id, count, style):
    """生成运维/事故日志型（带日期标题，测时间元数据与同名不同日期的竞争）。

    ⚠️ 每条日志必须**现象/根因各不相同**，否则 20 条日志彼此近乎重复，
    检索会随机命中其中一条（测出来的是"模板相似度"而不是"能不能定位到那一天"）。
    """
    # 20 天各一个**不同**事件：headed 用前 10 个，flat 用后 10 个。
    # 刻意不让两批共用同一批事件 —— 否则"巡检 230"与"巡检 240"内容几乎相同，
    # 检索会命中同内容的那一份（那测的是模板相似度，不是定位能力）。
    EVENTS = [
        ('磁盘使用率 85%', '清理 7 天前的日志归档', '日志保留策略需要按业务分级'),
        ('JVM Full GC 频繁', '把堆从 4G 调到 6G 并换了 GC 算法', '需要建立 GC 指标告警'),
        ('MySQL 主从延迟 8 秒', '大事务拆成小批次提交', '禁止单事务更新超过一万行'),
        ('接口 P99 突然翻倍', '发现是新上的埋点同步写日志导致', '埋点必须异步'),
        ('Redis 内存打满触发淘汰', '给热点 key 设置合理过期时间', '必须监控 evicted_keys'),
        ('连接池被打满', '临时把池从 20 调到 50', '池大小需要与数据库上限联动评估'),
        ('消息队列堆积到 200 万条', '紧急扩容消费者实例', '消费速率要预留 3 倍余量'),
        ('某台机器 CPU 100%', '定位到死循环的定时任务并修复', '定时任务要加超时与熔断'),
        ('证书过期导致调用失败', '紧急续签并重启网关', '证书到期需要提前 30 天告警'),
        ('缓存穿透打挂数据库', '加空值缓存并引入布隆过滤器', '缓存必须考虑不存在的 key'),
        # --- flat 系列专用（与上面不重复）---
        ('网关 502 比例升到 12%', '回滚了当天的路由配置变更', '路由配置要能一键回滚'),
        ('定时任务重复执行了两次', '给任务加了分布式锁', '定时任务必须幂等'),
        ('某接口返回体体积暴涨 20 倍', '给接口加了字段白名单', '接口返回体要有大小告警'),
        ('数据库磁盘写满', '归档了半年前的历史表', '大表需要定期归档而不是只加索引'),
        ('登录接口被撞库', '上线了按 IP 与账号双维度限流', '限流阈值要按业务区分'),
        ('日志采集 agent 挂掉', '加了 agent 存活探针与自动重启', '采集链路本身也要被监控'),
        ('某个分片数据倾斜严重', '把热点 key 加了随机后缀打散', '分片键要定期检查倾斜度'),
        ('CDN 回源率突然升到 90%', '修正了缓存键里带随机参数的 bug', '缓存键设计要评审'),
        ('批量导入任务把连接池占满', '给批量任务单独配了连接池', '批处理与在线流量要隔离'),
        ('某台机器时间漂移导致验签失败', '加了 NTP 校时与偏移告警', '涉及时间的逻辑要监控时钟偏移'),
    ]
    out = []
    # headed 系列取前 10 个事件，flat 系列取后 10 个，避免两批内容重复
    offset = 0 if style == 'headed' else 10
    for k in range(count):
        nid = start_id + k
        day = 1 + k
        symptom, action, todo = EVENTS[(offset + k) % len(EVENTS)]
        if style == 'headed':
            body = (f'# 巡检记录 - 2026-08-{day:02d}\n\n'
                    f'## 现象\n\n{day} 日凌晨发现{symptom}，触发告警。\n\n'
                    f'## 处置\n\n{action}，服务恢复正常。\n\n'
                    f'## 待改进\n\n{todo}。\n')
        else:
            body = (f'巡检 2026-08-{day:02d}: {symptom}，处置方式为{action}。'
                    f'同类问题的根因是{todo}，下一步按此整改。')
        out.append((nid, f'巡检记录 2026-08-{day:02d}', f'gen_incident_{style}',
                    f'2026-08-{day:02d}', body))
    return out


def _gen_qa_notes(start_id, topics, style):
    """生成问答对型笔记（记录型，chunk 应保留问与答的配对）。内容同样特异。"""
    out = []
    for k, d in enumerate(topics):
        nid = start_id + k
        title = d['t']
        if style == 'clean':
            body = (f'## 问：{title} 该怎么选？\n\n答：{d["gist"]}\n\n'
                    f'## 问：什么时候不适合用？\n\n答：{d["scene"]}\n\n'
                    f'## 问：有什么坑？\n\n答：{d["risk"]}\n')
        else:
            body = (f'Q: {title} 怎么选\nA: {d["gist"]}\n'
                    f'追问: 什么场景用\n补充: {d["scene"]}\n'
                    f'追问: 坑呢\n补充: {d["risk"]}\n')
        out.append((nid, f'问答：{title}', f'gen_qa_{style}', '2026-09-25', body))
    return out


def _generate_bulk():
    """批量生成，刻意混合三种结构复杂度与三种体裁。"""
    bulk = []
    bulk += _gen_template_notes(200, _TOPICS[:10], 'clean')
    bulk += _gen_template_notes(210, _TOPICS[10:20], 'messy')
    bulk += _gen_template_notes(220, _TOPICS[20:], 'deep')
    bulk += _gen_incident_logs(230, 10, 'headed')
    bulk += _gen_incident_logs(240, 10, 'flat')
    bulk += _gen_qa_notes(250, _TOPICS[:8], 'clean')
    bulk += _gen_qa_notes(260, _TOPICS[8:16], 'flat')
    return bulk


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dry-run', action='store_true', help='只打印统计，不写库')
    args = ap.parse_args()

    # 扩展到有统计意义的规模（12 条真实笔记只有 1.2 万 token，1 条 = 2.3 个点）。
    # 用手写 + 参数化生成两种方式：手写的那 20 条覆盖**特定脏法**，
    # 生成的那些补**规模**，且生成器刻意产出不同结构复杂度（有无标题/有无空行/长短）。
    N.extend(_generate_bulk())
    print(f'合成笔记 {len(N)} 条，共 {len(set(p for _, _, p, _, _ in N))} 种脏法\n')
    print(f'{"id":<6}{"脏法":<18}{"字数":<7}{"token":<7}{"切块数":<8}标题')
    print('-' * 88)
    tot_tok = tot_chunks = 0
    for nid, title, pattern, created, content in N:
        chunks = split_by_headings(content)
        t = _n_tokens(content)
        tot_tok += t
        tot_chunks += len(chunks)
        print(f'{nid:<6}{pattern:<18}{len(content):<7}{t:<7}{len(chunks):<8}{title[:32]}')
    print('-' * 88)
    print(f'合计 {len(N)} 条  {tot_tok} token  {tot_chunks} 块'
          f'（对比真实笔记 12 条 / 12181 token / 57 块）')

    print('\n按脏法聚合:')
    agg = {}
    for nid, title, pattern, created, content in N:
        a = agg.setdefault(pattern, [0, 0, 0])
        a[0] += 1
        a[1] += _n_tokens(content)
        a[2] += len(split_by_headings(content))
    for p, (n, t, c) in sorted(agg.items()):
        print(f'  {p:<18} {n} 条  {t:>5} token  {c:>3} 块')

    if args.dry_run:
        print('\n[dry-run] 未写库')
        return

    col = rag.chroma_client.get_or_create_collection(
        name=rag.get_collection_name(1, SYNTH_SUFFIX))
    ids, embs, docs, metas = [], [], [], []
    for nid, title, pattern, created, content in N:
        for i, (heading, body) in enumerate(split_by_headings(content)):
            embed_text = f'{title}\n{heading}\n{body}' if title else f'{heading}\n{body}'
            ids.append(f'{nid}:{i}')
            embs.append(rag.get_embedding(embed_text))
            docs.append(body)
            metas.append({'title': title, 'node_id': nid, 'chunk_index': i,
                          'heading': heading, 'pattern': pattern,
                          'synthetic': True,
                          # 合成笔记**不在 DB 里**，所以生产读路径的 _attach_note_dates
                          # 取不到日期。这里把日期写进 metadata，便于将来直接按 metadata
                          # 做时效性测试（不必回表）。
                          'note_date': created})
    existing = col.get()
    if existing['ids']:
        col.delete(ids=existing['ids'])
    col.upsert(ids=ids, embeddings=embs, documents=docs, metadatas=metas)
    print(f'\n[合成集合] {col.name}  {col.count()} 块（{len(N)} 条笔记）')
    print('⚠️ 该集合标注 synthetic=True，任何报告里必须与真实笔记分开统计')


if __name__ == '__main__':
    main()
